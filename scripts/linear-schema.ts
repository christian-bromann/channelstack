/**
 * `pnpm linear:schema`: Linear's GraphQL schema, for the fake. `schema.graphql` is Linear's own
 * file from its SDK's repository, committed as it is; this writes `schema.ts`, the module that
 * carries it into the binary (a compiled binary has no files next to it). `--check` fails when the
 * module doesn't match the file; `--fetch` first downloads the file again at `COMMIT`.
 */
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

import { ROOT } from "./lib/generate.ts";

/** The commit of linear/linear the schema is taken from, and the git blob SHA of the file there. */
const COMMIT = "2ca00918e3ae699a0aa1a6b07330b433397cd201";
const BLOB = "69ad47d85c00782afa1a42ad95d81b5ceddeee97";
const SOURCE = `https://raw.githubusercontent.com/linear/linear/${COMMIT}/packages/sdk/src/schema.graphql`;

const dir = join(ROOT, "server", "src", "drivers", "linear", "schema");
const sdlPath = join(dir, "schema.graphql");
const modulePath = join(dir, "schema.ts");

/** The SHA git gives a blob: what GitHub shows for the file, so the download can be checked against it. */
const blobSha = (bytes: Buffer) => createHash("sha1").update(`blob ${bytes.length}\0`).update(bytes).digest("hex");

const moduleFor = (sdl: string) =>
  [
    "// Generated by scripts/linear-schema.ts from schema.graphql. Do not edit: run `pnpm linear:schema`.",
    `// Linear's GraphQL schema, from linear/linear at ${COMMIT}.`,
    `export const LINEAR_SCHEMA: string = ${JSON.stringify(sdl)};`,
    "",
  ].join("\n");

const args = process.argv.slice(2);
if (args.includes("--fetch")) {
  const response = await fetch(SOURCE);
  if (!response.ok) throw new Error(`${SOURCE} answered ${response.status}`);
  const bytes = Buffer.from(await response.arrayBuffer());
  if (blobSha(bytes) !== BLOB) throw new Error(`The schema at ${COMMIT} isn't the blob ${BLOB}: update both together`);
  writeFileSync(sdlPath, bytes);
}
const sdl = readFileSync(sdlPath);
if (blobSha(sdl) !== BLOB)
  throw new Error(`${sdlPath} isn't Linear's file at ${COMMIT}: run \`pnpm linear:schema --fetch\``);
const expected = moduleFor(sdl.toString("utf8"));
if (args.includes("--check")) {
  let actual = "";
  try {
    actual = readFileSync(modulePath, "utf8");
  } catch {}
  if (actual !== expected) {
    console.error("linear:schema: schema.ts doesn't match schema.graphql. Run `pnpm linear:schema`.");
    process.exit(1);
  }
  console.log("linear:schema: schema.ts matches Linear's schema at", COMMIT);
} else {
  writeFileSync(modulePath, expected);
  console.log("linear:schema: wrote", modulePath);
}
