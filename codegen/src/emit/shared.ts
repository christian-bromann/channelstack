/** `not_in_room` → `NotInRoomError`. */
export function errorClassName(code: string): string {
  return `${code
    .split("_")
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join("")}Error`;
}

/** `botUserId` → `bot_user_id`. */
export function snakeCase(name: string): string {
  return name.replace(/[A-Z]/g, (letter) => `_${letter.toLowerCase()}`);
}

/** Lookups every emitter needs over the IR. */
export class IrIndex {
  readonly ir: Ir;
  readonly #resources: Map<string, IrResource>;
  readonly #types: Map<string, IrType>;
  readonly #printable: Set<string>;

  constructor(ir: Ir) {
    this.#printable = new Set(ir.types.filter((type) => type.stringField !== undefined).map((type) => type.name));
    this.ir = ir;
    this.#resources = new Map(ir.resources.map((resource) => [resource.name, resource]));
    this.#types = new Map(ir.types.map((type) => [type.name, type.type]));
  }

  resource(name: string): IrResource {
    const resource = this.#resources.get(name);
    if (!resource) throw new Error(`The IR has no resource "${name}"`);
    return resource;
  }

  /**
   * Does wire data of this type have to be converted before SDK users see it: handle data wrapped
   * into handles again, or a value that prints as text?
   */
  holdsResources(type: IrType | null, seen = new Set<string>()): boolean {
    if (!type) return false;
    switch (type.kind) {
      case "resource":
        return true;
      case "array":
        return this.holdsResources(type.items, seen);
      case "record":
        return this.holdsResources(type.values, seen);
      case "nullable":
        // `null` on the wire is "nothing" in the SDK, so the value is converted whatever it holds.
        return true;
      case "object":
        return type.fields.some((field) => this.holdsResources(field.type, seen));
      case "union":
        return type.types.some((member) => this.holdsResources(member, seen));
      case "named": {
        if (this.#printable.has(type.name)) return true;
        if (seen.has(type.name)) return false;
        seen.add(type.name);
        return this.holdsResources(this.#types.get(type.name) ?? null, seen);
      }
      default:
        return false;
    }
  }

  /** A resource's own fields: the ones it doesn't have from the resource it extends. */
  ownFields(resource: IrResource): IrResource["fields"] {
    if (resource.extends === undefined) return resource.fields;
    const inherited = new Set(this.resource(resource.extends).fields.map((field) => field.name));
    return resource.fields.filter((field) => !inherited.has(field.name));
  }

  /** Does a resource it extends, however far up, have a method or a wait of this name? */
  inherits(resource: IrResource, name: string): boolean {
    if (resource.extends === undefined) return false;
    const parent = this.resource(resource.extends);
    return (
      parent.methods.some((method) => method.name === name) ||
      (parent.waits ?? []).some((wait) => wait.name === name) ||
      this.inherits(parent, name)
    );
  }

  /** The id fields of the resources a `ref` accepts, with their types. */
  refIds(resources: readonly string[]): IrResource["fields"] {
    const [first = ""] = resources;
    const fields = this.resource(first).fields;
    return this.refIdFields(resources).flatMap((id) => fields.find((field) => field.name === id) ?? []);
  }

  /** The id fields shared by the resources a `ref` accepts: what gets sent in place of the handle. */
  refIdFields(resources: readonly string[]): string[] {
    const [first, ...rest] = resources.map((name) => this.resource(name).idFields ?? []);
    if (first === undefined || first.length === 0 || rest.some((fields) => fields.join() !== first.join())) {
      throw new Error(`A reference to ${resources.join(" | ")} needs resources that share the same id fields`);
    }
    return first;
  }

  /** In a union of handles, the value of the discriminator field for each member: what tells their data apart. */
  discriminated(type: Extract<IrType, { kind: "union" }>): Array<{ value: string; member: IrType }> | undefined {
    const { discriminator } = type;
    if (discriminator === undefined) return undefined;
    const tagged = type.types.map((member) => {
      const field =
        member.kind === "resource"
          ? this.resource(member.name).fields.find((candidate) => candidate.name === discriminator)
          : undefined;
      // A discriminator is a text tag (`kind: "user"`); a boolean literal doesn't tell handles apart.
      return field?.type.kind === "literal" && typeof field.type.value === "string"
        ? { value: field.type.value, member }
        : undefined;
    });
    return tagged.every((entry) => entry !== undefined) ? tagged : undefined;
  }

  /** The method SDKs call when a handle is disposed, if the resource has one. */
  disposer(resource: IrResource): IrMethod | undefined {
    return resource.methods.find((method) => method.dispose);
  }
}

/** A URL path as template parts: literal text, and the path parameters between it. */
export function pathParts(method: IrMethod): Array<string | IrMethod["http"]["pathParams"][number]> {
  return method.http.path
    .split(/(\{[^}]+\})/)
    .filter((part) => part !== "")
    .map((part) => {
      if (!part.startsWith("{")) return part;
      const param = method.http.pathParams.find((candidate) => candidate.name === part.slice(1, -1));
      if (!param) throw new Error(`${method.http.path} has no binding for ${part}`);
      return param;
    });
}
